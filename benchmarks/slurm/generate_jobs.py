"""Generate lot 8's SLURM job scripts (docs/reports/plan_lot8.md §1.5, §0.11).

16 scripts: 2 calibration jobs + 14 training jobs ({resnet50, vit_small} x 7 arms). They are
near-identical apart from the model, the arm and the ``--time`` budget, so they are generated
rather than hand-maintained — the same convention as the sibling repository's own
``scripts/generate_ablation_configs.py``.

    python benchmarks/slurm/generate_jobs.py        # regenerates every .sh in this directory

Every cluster-specific line (account, GPU shape, module load, no-internet assumption) is copied
from job scripts that have actually run on this cluster
(``/Users/baolgr/Documents/AtlasAnalyticsLab/experiments/*/slurm/``), not re-derived — see
``README.md`` in this directory for the provenance of each.
"""

from __future__ import annotations

from pathlib import Path

SLURM_DIR = Path(__file__).resolve().parent

MODELS = {
    # display, --time for a training job, --time for the calibration job, per-epoch anchor
    "resnet50": ("ResNet50", "04:00:00", "00:45:00"),
    "vit_small": ("ViT-S/4", "01:30:00", "00:30:00"),
}
ARMS = ("diag", "kfac", "ekfac", "tkfac", "tekfac", "adam", "adamw")
REFERENCE_ARM = "diag"
EPOCHS = 50

HEADER = """#!/bin/bash
# {title}
# Generated by benchmarks/slurm/generate_jobs.py — edit that file, not this one.
# See docs/reports/plan_lot8.md §0.11/§1.5 and benchmarks/slurm/README.md.
# Submit from the repository root:  sbatch benchmarks/slurm/{filename}

#SBATCH --account=def-msh-ab
#SBATCH --job-name={job_name}
#SBATCH --gpus=h100_1g.10gb:1
#SBATCH --cpus-per-task=8
#SBATCH --mem=16G
#SBATCH --time={time}
#SBATCH --output=benchmarks/slurm/logs/%x-%j.out

# --time: {time_basis}

set -euo pipefail
cd "$SLURM_SUBMIT_DIR"

module purge
module load StdEnv/2023 gcc/13.3 cuda/12.6 python/3.11.5

virtualenv --no-download "$SLURM_TMPDIR/env"
source "$SLURM_TMPDIR/env/bin/activate"
pip install --no-index --upgrade pip
pip install --no-index -r requirements-cluster.txt

export PYTHONPATH="$SLURM_SUBMIT_DIR/src"

"""

TIME_BASIS = (
    "UNMEASURED extrapolation until benchmarks/slurm/calibrate_{model}.sh has run once.\n"
    "# Basis: real sacct numbers for the same model, batch size and dataset on this cluster, in\n"
    "# /Users/baolgr/Documents/AtlasAnalyticsLab/experiments/default/slurm/README.md\n"
    "# ({anchor}).\n"
    "# Under the WCT protocol every arm takes ~the reference arm's\n"
    "# wall-clock time, so all seven arms of one model share one budget. Re-tighten from real\n"
    "# sacct data after the first submission."
)
ANCHORS = {
    "resnet50": "~85 min for 40 epochs of ResNet50/AdamW -> ~2.1 min/epoch -> ~1h45 at 50 epochs",
    "vit_small": "20-22 min for 40 epochs of ViT-small -> ~0.55 min/epoch -> ~28 min at 50 epochs",
}

CALIBRATION_BODY = """# Calibration (plan_lot8.md §3 step 3): 2 short epochs of every arm, on a 5000-image training
# subset, printing per-arm steps/s, median step time and peak CUDA memory. Its job is to turn the
# 14 training scripts' --time values from extrapolations into measurements, and to confirm the
# memory decisions of plan_lot8.md §0.4 (fisher_batch_samples) and §0.5 (conv_sua) keep every arm
# inside the 10 GB MIG slice. Run this BEFORE the training jobs.
python benchmarks/cifar10_classification.py \\
  --model {model} \\
  --arms diag kfac ekfac tkfac tekfac adam adamw \\
  --epochs 2 \\
  --budget-mode epochs \\
  --train-subset 5000 \\
  --num-workers 8 \\
  --no-allow-download \\
  --data-root "$SLURM_SUBMIT_DIR/dataset" \\
  --output-dir "$SLURM_SUBMIT_DIR/benchmarks/outputs/lot8_cifar10/{model}/_calibration"
"""

REFERENCE_BODY = """# Reference arm (plan_lot8.md §0.7): a fixed {epochs}-epoch run whose measured elapsed time is
# every other arm's wall-clock budget. Read it back from the run's manifest.json:
#   python -c "import json;print(json.load(open('benchmarks/outputs/lot8_cifar10/{model}/{arm}/manifest.json'))['arms']['{arm}']['total_s'])"
# and pass it to the other six jobs as --wct-budget (they default to WCT_BUDGET below).
python benchmarks/cifar10_classification.py \\
  --model {model} \\
  --arms {arm} \\
  --epochs {epochs} \\
  --budget-mode epochs \\
  --num-workers 8 \\
  --no-allow-download \\
  --data-root "$SLURM_SUBMIT_DIR/dataset" \\
  --output-dir "$SLURM_SUBMIT_DIR/benchmarks/outputs/lot8_cifar10/{model}/{arm}"
"""

BUDGETED_BODY = """# One WCT-budgeted arm (plan_lot8.md §0.7). WCT_BUDGET is the reference arm's measured elapsed
# time in seconds; override it at submission time once the reference job has run:
#   sbatch --export=ALL,WCT_BUDGET=6543 benchmarks/slurm/{filename}
# Leaving it unset falls back to --budget-mode epochs, i.e. the (deliberately rigged, plan.md
# §6.3) equal-epoch comparison — usable, but not this lot's headline protocol.
WCT_BUDGET="${{WCT_BUDGET:-}}"
if [ -n "$WCT_BUDGET" ]; then
  BUDGET_ARGS=(--budget-mode wct --wct-budget "$WCT_BUDGET" --max-epoch-factor 3)
else
  echo "WCT_BUDGET unset — falling back to --budget-mode epochs (see this script's header)" >&2
  BUDGET_ARGS=(--budget-mode epochs)
fi

python benchmarks/cifar10_classification.py \\
  --model {model} \\
  --arms {arm} \\
  --epochs {epochs} \\
  "${{BUDGET_ARGS[@]}}" \\
  --num-workers 8 \\
  --no-allow-download \\
  --data-root "$SLURM_SUBMIT_DIR/dataset" \\
  --output-dir "$SLURM_SUBMIT_DIR/benchmarks/outputs/lot8_cifar10/{model}/{arm}"
"""


def write(filename: str, text: str) -> None:
    path = SLURM_DIR / filename
    path.write_text(text)
    path.chmod(0o755)
    print(f"wrote {path.relative_to(SLURM_DIR.parents[1])}")


def main() -> None:
    for model, (display, train_time, calib_time) in MODELS.items():
        basis = TIME_BASIS.format(model=model, anchor=ANCHORS[model])
        write(
            f"calibrate_{model}.sh",
            HEADER.format(
                title=f"CIFAR-10 / {display}: calibration pass, all 7 arms, 2 epochs on a 5k subset.",
                filename=f"calibrate_{model}.sh",
                job_name=f"cal_{model}",
                time=calib_time,
                time_basis=(
                    "2 epochs x 7 arms on a 5000-image subset; dominated by env setup and the "
                    "first-step\n# hook/eigendecomposition warm-up, not by training. Generous on "
                    "purpose."
                ),
            )
            + CALIBRATION_BODY.format(model=model),
        )
        for arm in ARMS:
            filename = f"train_{model}_{arm}.sh"
            body = (
                REFERENCE_BODY.format(model=model, arm=arm, epochs=EPOCHS)
                if arm == REFERENCE_ARM
                else BUDGETED_BODY.format(model=model, arm=arm, epochs=EPOCHS, filename=filename)
            )
            write(
                filename,
                HEADER.format(
                    title=(
                        f"CIFAR-10 / {display}, arm={arm}"
                        + (" (WCT reference arm)" if arm == REFERENCE_ARM else "")
                        + f". Writes to benchmarks/outputs/lot8_cifar10/{model}/{arm}/."
                    ),
                    filename=filename,
                    job_name=f"{model}_{arm}",
                    time=train_time,
                    time_basis=basis,
                )
                + body,
            )


if __name__ == "__main__":
    main()
